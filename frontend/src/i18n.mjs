function interpolate(template, params) {
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  ));
}

export function t(key, params = {}) {
  const table = isZh ? zh : en;
  return interpolate(table[key] ?? zh[key] ?? key, params);
}

export function hasTranslation(key) {
  return Object.prototype.hasOwnProperty.call(zh, key) && Object.prototype.hasOwnProperty.call(enOverrides, key);
}

// reasoningEffortLabel returns the raw thinking-strength parameter value
// (auto/low/medium/high/xhigh/max) as the UI label. These levels are
// provider parameter names and are intentionally not localized — what the
// user picks is exactly what gets sent. Unknown values fall back to "auto".
export function reasoningEffortLabel(level) {
  const v = String(level || 'auto').trim().toLowerCase();
  return ['auto', 'low', 'medium', 'high', 'xhigh', 'max'].includes(v) ? v : 'auto';
}

export function formatDateTime(value, options) {
  const date = value instanceof Date ? value : new Date(value);
  const resolvedOptions = options || {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  };
  return new Intl.DateTimeFormat(locale, resolvedOptions).format(date);
}

export function welcomeGreeting(now = new Date()) {
  const groups = greetingGroups[locale] || greetingGroups[LOCALE_EN_US];
  const hour = now.getHours();
  const group = groups.find((item) => hour >= item.start && hour < item.end) || groups[0];
  const seed = now.getFullYear() * 10000 + (now.getMonth() + 1) * 100 + now.getDate() + hour;
  const greeting = group.lines[seed % group.lines.length];
  const hh = String(hour).padStart(2, '0');
  const mm = String(now.getMinutes()).padStart(2, '0');
  if (isZh) {
    const days = ['日', '一', '二', '三', '四', '五', '六'];
    return `今天是 ${now.getMonth() + 1}月${now.getDate()}日 周${days[now.getDay()]}，现在是 ${hh}:${mm}。${greeting}`;
  }
  const date = formatDateTime(now, { month: 'long', day: 'numeric', weekday: 'short' });
  return `It is ${date}, ${hh}:${mm}. ${greeting}`;
}
