//go:build ignore

// Regenerate the fixed-text lookup after editing the catalogs:
// go run scripts/i18n.go && go tool mygo generate
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/egoist/mygo/i18n"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	catalog, err := i18n.NewCatalog(os.DirFS("locales"), "en")
	if err != nil {
		return err
	}
	data, err := os.ReadFile("locales/zh-Hans.json")
	if err != nil {
		return err
	}
	var entries map[string]json.RawMessage
	if err := json.Unmarshal(data, &entries); err != nil {
		return err
	}
	keys := []string{}
	for key := range entries {
		if strings.HasPrefix(key, "ui_") {
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	var out bytes.Buffer
	out.WriteString("// Code generated by go run scripts/i18n.go. DO NOT EDIT.\npackage locales\n\nvar sourceKeys = map[string]string{\n")
	seen := map[string]string{}
	for _, key := range keys {
		message, tag, ok := catalog.Message("zh-Hans", key)
		if !ok || tag != "zh-Hans" {
			return fmt.Errorf("invalid source message %s", key)
		}
		source := message.Format("zh-Hans", nil)
		if previous, exists := seen[source]; exists {
			return fmt.Errorf("duplicate source in %s and %s", previous, key)
		}
		seen[source] = key
		fmt.Fprintf(&out, "%s: %s,\n", strconv.Quote(source), strconv.Quote(key))
	}
	out.WriteString("}\n")
	code, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("locales/source_keys_gen.go", code, 0644)
}
